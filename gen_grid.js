const text = 'OPEN TO WORK';
const rows = [0,1,2,3,4,5,6].map(r => {
  let s = '..';
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (c === ' ') {
      s += '......';
    } else {
      s += L[c][r];
      if (i < text.length - 1 && text[i + 1] !== ' ') s += '...';
    }
  }
  s += '..';
  return s;
});

